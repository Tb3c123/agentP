"""
agentP - CLI Bridge Service (Sprint 6)
Injects proxy configurations and environment variables for external developer CLI tools
(Claude Code CLI, Cursor IDE, Codex, Gemini CLI, Aider, Cline) into agentP Core Daemon.
Zero external npm/docker dependencies required.
Author: Lucas (Senior Dev) & Alex (PM)
"""

import os
import shutil
import json
from typing import Dict, Any, List

class CliBridgeService:
    """Manages CLI environment injection and tool configuration generators."""

    BRIDGE_PORT = 9090
    BRIDGE_HOST = "127.0.0.1"
    AUTH_TOKEN = "agentp-core-bridge-key"

    @classmethod
    def get_base_url(cls) -> str:
        return f"http://{cls.BRIDGE_HOST}:{cls.BRIDGE_PORT}"

    @classmethod
    def get_v1_url(cls) -> str:
        return f"http://{cls.BRIDGE_HOST}:{cls.BRIDGE_PORT}/v1"

    @classmethod
    def detect_installed_tools(cls) -> Dict[str, Dict[str, Any]]:
        """Detects whether developer CLI tools are installed on the local system."""
        tools = {
            "claude_code": {
                "name": "Claude Code CLI",
                "binary": "claude",
                "installed": shutil.which("claude") is not None,
                "protocol": "Anthropic /v1/messages",
                "env_vars": {
                    "ANTHROPIC_BASE_URL": cls.get_base_url(),
                    "ANTHROPIC_API_KEY": cls.AUTH_TOKEN
                }
            },
            "cursor": {
                "name": "Cursor IDE Bridge",
                "binary": "cursor",
                "installed": shutil.which("cursor") is not None or os.path.exists("/Applications/Cursor.app"),
                "protocol": "OpenAI /v1/chat/completions",
                "env_vars": {
                    "OPENAI_BASE_URL": cls.get_v1_url(),
                    "OPENAI_API_KEY": cls.AUTH_TOKEN
                }
            },
            "gemini_cli": {
                "name": "Gemini CLI Tool",
                "binary": "gemini",
                "installed": shutil.which("gemini") is not None,
                "protocol": "Gemini REST",
                "env_vars": {
                    "GEMINI_BASE_URL": cls.get_base_url()
                }
            },
            "aider": {
                "name": "Aider CLI",
                "binary": "aider",
                "installed": shutil.which("aider") is not None,
                "protocol": "OpenAI /v1",
                "env_vars": {
                    "OPENAI_API_BASE": cls.get_v1_url(),
                    "OPENAI_API_KEY": cls.AUTH_TOKEN
                }
            }
        }
        return tools

    @classmethod
    def generate_shell_export_script(cls) -> str:
        """Generates a POSIX shell script to activate agentP CLI routing."""
        base_url = cls.get_base_url()
        v1_url = cls.get_v1_url()
        token = cls.AUTH_TOKEN

        script = f"""#!/bin/sh
# agentP CLI Bridge Activation Script
# Auto-generated by agentP Core Daemon (Sprint 6)
# Routes Claude Code, Cursor, and Aider through local agentP daemon (Port {cls.BRIDGE_PORT})

export ANTHROPIC_BASE_URL="{base_url}"
export ANTHROPIC_API_KEY="{token}"
export OPENAI_BASE_URL="{v1_url}"
export OPENAI_API_BASE="{v1_url}"
export OPENAI_API_KEY="{token}"

echo "✓ agentP CLI Bridge Activated! (Proxy: {base_url})"
echo "  • Claude Code CLI  -> {base_url}/v1/messages"
echo "  • Cursor / OpenAI  -> {v1_url}/chat/completions"
"""
        return script

    @classmethod
    def generate_cursor_config(cls) -> Dict[str, Any]:
        """Generates Cursor IDE configuration snippet for custom models."""
        return {
            "openai_base_url": cls.get_v1_url(),
            "api_key": cls.AUTH_TOKEN,
            "models": [
                "claude-3-7-sonnet",
                "claude-3-5-sonnet",
                "deepseek-r1",
                "deepseek-v3",
                "gpt-4o",
                "qwen-2-5-coder"
            ],
            "override_api": True
        }

    @classmethod
    def write_bridge_scripts(cls, project_dir: str = ".") -> Dict[str, str]:
        """Persists activation scripts to .agents/bin/."""
        bin_dir = os.path.join(project_dir, ".agents", "bin")
        os.makedirs(bin_dir, exist_ok=True)

        sh_path = os.path.join(bin_dir, "activate_bridge.sh")
        cursor_path = os.path.join(bin_dir, "cursor_config.json")

        script_content = cls.generate_shell_export_script()
        with open(sh_path, "w", encoding="utf-8") as f:
            f.write(script_content)
        try:
            os.chmod(sh_path, 0o755)
        except Exception:
            pass

        with open(cursor_path, "w", encoding="utf-8") as f:
            json.dump(cls.generate_cursor_config(), f, indent=2)

        return {
            "shell_script": sh_path,
            "cursor_config": cursor_path
        }
